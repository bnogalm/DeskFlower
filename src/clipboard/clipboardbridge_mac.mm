// The legacy multi-file type (one property list of paths on a single item), still read by Finder:
// what a copy without its list of names (unlisted) offers, the number of items being unknown.
NSPasteboardType const kFilenamesType = @"NSFilenamesPboardType";

// nspasteboard.org markers: clipboard managers and history tools leave such content alone.
NSPasteboardType const kTransientType = @"org.nspasteboard.TransientType";
NSPasteboardType const kConcealedType = @"org.nspasteboard.ConcealedType";
NSPasteboardType const kAutoGeneratedType = @"org.nspasteboard.AutoGeneratedType";

// Renders in progress (provideDataForType, which may wait for the service in a nested event loop):
// ClipboardBridge defers a pasteboard replacement meanwhile (see rendering()).
int s_rendering = 0;
struct RenderScope {
    RenderScope() { ++s_rendering; }
    ~RenderScope() { --s_rendering; }
};

// Shared by the items of one sealed clipboard: what renders them, and the files once transferred.
struct SealedState {
    // After a refused, failed or still running transfer, the other items of the same paste (Finder
    // reads them one after another) give up at once instead of asking (and waiting) again each.
    static constexpr int kSamePasteMs = 1500;

    // A short wait after a read that was no paste or a refused format (the real paste may follow
    // at once); after a failed or refused transfer, once the other items of that paste gave up.
    static constexpr int kRepublishSoonMs = 300;
    static constexpr int kRepublishAfterPasteMs = kSamePasteMs + 100;

    ClipboardBridge::UnsealFormat unseal;
    ClipboardBridge::FetchFiles fetch;
    std::function<void(int delayMs)> unprovided;
    bool lastWasNoPaste = false; // the last failed ensureFetched was a read that was no paste
    QStringList names;   // top-level files and folders, one pasteboard item each
    QStringList fetched; // their local paths, once transferred (kept: Finder reads item by item)
    QDeadlineTimer failedRecently{QDeadlineTimer::Forever};
    bool failed = false;

    // Transfers everything at the first request. False if the transfer was refused or failed (not
    // remembered beyond the paste in progress: the next paste asks again). A read that was no
    // paste (kNotAPaste: a reader looking at the pasteboard) is not even remembered for the paste
    // in progress: the real paste that follows, a moment later, must get through.
    bool ensureFetched()
    {
        if (!fetched.isEmpty())
            return true;
        if (failed && !failedRecently.hasExpired())
            return false;
        lastWasNoPaste = false;
        QString error;
        fetched = fetch ? fetch(&error) : QStringList();
        if (!fetched.isEmpty())
            return true;
        if (error == QLatin1String(ClipboardBridge::kNotAPaste)) {
            qCInfo(lcClipBridge) << "Copied files not transferred: not a paste";
            failed = false;
            lastWasNoPaste = true;
            return false;
        }
        qCWarning(lcClipBridge) << "Paste failed:" << error;
        failed = true;
        failedRecently.setRemainingTime(kSamePasteMs); // from the end of the attempt
        return false;
    }

    // Nothing was provided for a type: the items are written again a moment later (see the header).
    void nothingProvided(int delayMs) const
    {
        if (unprovided)
            unprovided(delayMs);
    }
    int filesRetryMs() const { return lastWasNoPaste ? kRepublishSoonMs : kRepublishAfterPasteMs; }

    // The local path of item `index`; empty if the transfer was refused or failed.
    QString pathOf(int index)
    {
        if (!ensureFetched())
            return {};
        // Matched by name (the transfer keeps the names); by position as a fallback.
        const QString name = names.value(index);
        for (const QString &path : std::as_const(fetched)) {
            if (QFileInfo(path).fileName() == name)
                return path;
        }
        return fetched.value(index);
    }
};

NSPasteboardType pasteboardType(const QString &mime)
{
    if (mime == QLatin1String("text/plain"))
        return NSPasteboardTypeString;
    if (mime == QLatin1String("text/html"))
        return NSPasteboardTypeHTML;
    if (mime == QLatin1String("image/png"))
        return NSPasteboardTypePNG;
    return nil;
}

QString mimeOf(NSPasteboardType type)
{
    if ([type isEqualToString:NSPasteboardTypeString])
        return QStringLiteral("text/plain");
    if ([type isEqualToString:NSPasteboardTypeHTML])
        return QStringLiteral("text/html");
    if ([type isEqualToString:NSPasteboardTypePNG])
        return QStringLiteral("image/png");
    return {};
}

} // namespace

// Renders one item of a sealed clipboard when an application asks for one of its types.
@interface DFSealedItemProvider : NSObject <NSPasteboardItemDataProvider>
- (instancetype)initWithState:(const std::shared_ptr<SealedState> &)state index:(int)index;
@end

@implementation DFSealedItemProvider {
    std::shared_ptr<SealedState> _state;
    int _index;
}

- (instancetype)initWithState:(const std::shared_ptr<SealedState> &)state index:(int)index
{
    self = [super init];
    if (self) {
        _state = state;
        _index = index;
    }
    return self;
}

- (void)pasteboard:(NSPasteboard *)pasteboard item:(NSPasteboardItem *)item provideDataForType:(NSPasteboardType)type
{
    (void)pasteboard;
    const RenderScope rendering;
    // The render may wait for the service in a nested event loop, during which the clipboard can
    // be replaced (and this provider released): both stay alive until it returns.
    DFSealedItemProvider *keepAlive = self;
    (void)keepAlive;
    const std::shared_ptr<SealedState> state = _state;
    if ([type isEqualToString:kFilenamesType]) {
        if (!state->ensureFetched()) {
            state->nothingProvided(state->filesRetryMs());
            return;
        }
        NSMutableArray<NSString *> *paths = [NSMutableArray arrayWithCapacity:NSUInteger(state->fetched.size())];
        for (const QString &path : std::as_const(state->fetched))
            [paths addObject:path.toNSString()];
        [item setPropertyList:paths forType:kFilenamesType];
        return;
    }
    if ([type isEqualToString:NSPasteboardTypeFileURL]) {
        const QString path = state->pathOf(_index);
        if (path.isEmpty()) {
            state->nothingProvided(state->filesRetryMs()); // refused or failed: fresh items next time
            return;
        }
        NSURL *url = [NSURL fileURLWithPath:path.toNSString() isDirectory:QFileInfo(path).isDir()];
        [item setString:[url absoluteString] forType:NSPasteboardTypeFileURL];
        return;
    }
    const QString mime = mimeOf(type);
    if (mime.isEmpty() || !state->unseal)
        return;
    QString error;
    const QByteArray plain = state->unseal(mime, &error);
    if (plain.isEmpty()) {
        state->nothingProvided(SealedState::kRepublishSoonMs); // refused: fresh items next time
        return;
    }
    [item setData:plain.toNSData() forType:type];
}

@end

