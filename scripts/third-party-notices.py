#!/usr/bin/env python3
"""Lists the third-party components inside the Qt files that Deskflower ships.

Usage: python scripts/third-party-notices.py <qt prefix> <deployed folder> > licenses/qt-components.md
  e.g. python scripts/third-party-notices.py C:/Qt/6.11.2/msvc2022_64 dist/Deskflower

Reads the SPDX SBOMs that Qt installs in <qt prefix>/sbom, finds which Qt package each deployed
DLL belongs to and follows its dependencies to the bundled third-party code (zlib, libpng,
FreeType, HarfBuzz, PCRE2...). Run it again after upgrading Qt or changing the deployed modules,
and fetch the texts of any new SPDX license identifier into licenses/ (see THIRD-PARTY-NOTICES.md).
"""
import json
import pathlib
import sys
from collections import defaultdict


def main():
    qt, deployed = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    shipped = {p.name.lower() for p in deployed.rglob('*') if p.suffix.lower() in ('.dll', '.exe')}

    components = {}  # name -> (version, license, copyright, used by)
    used_by = defaultdict(set)
    extracted = {}
    modules = set()
    for sbom in sorted((qt / 'sbom').glob('*.spdx.json')):
        doc = json.loads(sbom.read_text(encoding='utf-8'))
        packages = {p['SPDXID']: p for p in doc['packages']}
        files = {f['SPDXID']: pathlib.PurePosixPath(f['fileName']).name.lower() for f in doc.get('files', [])}
        depends = defaultdict(list)
        roots = set()
        for r in doc['relationships']:
            if r['relationshipType'] == 'DEPENDS_ON':
                depends[r['spdxElementId']].append(r['relatedSpdxElement'])
            elif r['relationshipType'] == 'CONTAINS' and files.get(r['relatedSpdxElement']) in shipped:
                roots.add(r['spdxElementId'])
        for e in doc.get('hasExtractedLicensingInfos', []):
            extracted[e['licenseId']] = e['extractedText']

        for root in roots:
            modules.add(f"{packages[root]['name']} ({sbom.name.split('-')[0]})")
            seen, todo = set(), [root]
            while todo:
                pid = todo.pop()
                if pid in seen or pid not in packages:
                    continue
                seen.add(pid)
                todo.extend(depends[pid])
                p = packages[pid]
                if '3rdparty' not in pid:
                    continue
                name = p['name'].split('_Attribution_')[-1].removeprefix('Bundled')
                components[name.lower()] = (name, p.get('versionInfo', ''),
                                            p.get('licenseConcluded') or p.get('licenseDeclared', ''),
                                            p.get('copyrightText', ''))
                used_by[name.lower()].add(packages[root]['name'])

    out = ['# Third-party components inside the shipped Qt libraries', '',
           'Generated by `scripts/third-party-notices.py` from the SBOMs of Qt '
           f'({qt.name}), for the Qt files in the DeskFlower package.', '',
           'Shipped Qt packages: ' + ', '.join(sorted(modules)) + '.', '']
    for key in sorted(components):
        name, version, lic, copyright_text = components[key]
        out += [f'## {name}' + (f' {version}' if version and version != 'NOASSERTION' else ''), '',
                f'- License: `{lic}`',
                f'- Used by: {", ".join(sorted(used_by[key]))}', '']
        if copyright_text and copyright_text not in ('NOASSERTION', 'NONE'):
            out += ['```', copyright_text.strip(), '```', '']
    used_refs = sorted(r for r in extracted if any(r in c[2] for c in components.values()))
    if used_refs:
        out += ['# Licenses not in the SPDX list', '']
        for ref in used_refs:
            out += [f'## {ref}', '', '```', extracted[ref].strip(), '```', '']
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
